def jobs_as_dicts() -> list[dict]:
    return [job.as_dict() for job in JOBS]


def render_blueprint() -> str:
    payload = {
        "name": "family-cfo",
        "description": "Family CFO 定时任务（默认全部 disabled，需要用户逐项启用）",
        "jobs": jobs_as_dicts(),
    }
    return yaml.safe_dump(payload, allow_unicode=True, sort_keys=False)


def render_crontab(command_prefix: str = "family-cfo") -> str:
    lines = [
        "# Family CFO automation — review before installing",
        "# Generated by `family-cfo automation install --yes`",
    ]
    for job in JOBS:
        command = job.command.replace("family-cfo", command_prefix, 1)
        lines.append(f"{job.schedule}  {command}  # {job.title}")
    return "\n".join(lines) + "\n"


def install_schedule(dest_dir: str | Path, *, confirmed: bool, command_prefix: str = "family-cfo") -> dict:
    if not confirmed:
        raise ValidationError(
            "定时任务默认关闭；必须由用户确认后才能启用（使用 --yes）。"
        )
    dest = Path(dest_dir)
    dest.mkdir(parents=True, exist_ok=True)
    blueprint = dest / "family-cfo.yaml"
    crontab = dest / "family-cfo.crontab"
    blueprint.write_text(render_blueprint(), encoding="utf-8")
    crontab.write_text(render_crontab(command_prefix), encoding="utf-8")
    return {"blueprint": str(blueprint), "crontab": str(crontab), "jobs": len(JOBS)}
