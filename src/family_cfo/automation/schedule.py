"""Configurable automation jobs.

Nothing is enabled automatically.  ``install`` requires an explicit
``confirmed=True`` (CLI ``--yes``) and writes both a Hermes blueprint file and a
plain crontab snippet so the user can choose the runtime they actually use.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import yaml

from ..core.errors import ValidationError


@dataclass
class AutomationJob:
    id: str
    schedule: str
    title: str
    command: str
    prompt: str
    description: str
    enabled_by_default: bool = False

    def as_dict(self) -> dict:
        return {
            "id": self.id,
            "schedule": self.schedule,
            "title": self.title,
            "command": self.command,
            "prompt": self.prompt,
            "description": self.description,
            "enabled": False,
        }


